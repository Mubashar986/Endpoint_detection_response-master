# ==========================================

class EnrollmentToken(Document):
    """
    Secure token for agent onboarding.
    Generated by admin, used once during agent installation.
    """
    token = StringField(required=True, unique=True, default=lambda: secrets.token_hex(32))
    description = StringField(default="")
    expires_at = DateTimeField()  # Optional expiry
    max_uses = IntField(default=1)  # -1 for unlimited
    current_uses = IntField(default=0)
    is_active = BooleanField(default=True)
    created_by = StringField(required=True)  # Username of admin who created
    created_at = DateTimeField(default=lambda: datetime.now(timezone.utc))
    
    meta = {
        'collection': 'enrollment_tokens',
        'indexes': ['token', 'is_active', '-created_at']
    }
    
    def is_valid(self):
        """Check if token can still be used."""
        if not self.is_active:
            return False
        if self.expires_at:
            # Handle both timezone-aware and naive datetimes
            # MongoDB may store as naive, so we make expires_at aware if needed
            expires = self.expires_at
            if expires.tzinfo is None:
                # Naive datetime - assume it's UTC
                expires = expires.replace(tzinfo=timezone.utc)
            if datetime.now(timezone.utc) > expires:
                return False
        if self.max_uses != -1 and self.current_uses >= self.max_uses:
            return False
        return True
    
    def increment_usage(self):
        """Mark one use of the token."""
        self.current_uses += 1
        self.save()
    
    def __str__(self):
        return f"{self.token[:8]}... ({self.description})"


class AgentConfig(Document):
    """
    Versioned configuration policy for agents.
    Stores module settings, telemetry intervals, exclusions etc.
    """
    config_id = StringField(required=True, unique=True, default=lambda: str(uuid.uuid4()))
    name = StringField(default="Default Policy")
    version = IntField(default=1)
    
    # The actual JSON payload sent to agents
    config_json = DictField(default=lambda: {
        "modules": {
            "file_monitor": {"enabled": True},
            "process_monitor": {"enabled": True},
            "network_monitor": {"enabled": False}
        },
        "telemetry": {
            "batch_size": 100,
            "heartbeat_interval": 30
        }
    })
    
    created_by = StringField()  # Username
    created_at = DateTimeField(default=lambda: datetime.now(timezone.utc))
    
    meta = {
        'collection': 'agent_configs',
        'indexes': ['name', 'version', '-created_at']
    }
    
    def __str__(self):
        return f"{self.name} v{self.version}"


